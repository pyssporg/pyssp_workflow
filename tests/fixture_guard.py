"""Session guard: the test tree is read-only during a run.

This suite commits no fixture data, so there is no fixture directory to guard.
The guard instead covers the whole ``tests/`` tree: a test that writes a
``.ssd``, ``.ssv``, or ``.json`` beside the test files instead of into
``tmp_path`` changes the tree, and the session fails at finish naming the
paths. ``__pycache__`` and ``*.pyc`` are ignored because pytest owns them.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

_TESTS = Path(__file__).resolve().parent

#: The whole test tree; nothing under it is generated by the suite.
GUARDED_ROOTS = (_TESTS,)

_STATE: dict[Path, dict[str, str]] = {}


def _digest(root: Path) -> dict[str, str]:
    return {
        p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in sorted(root.rglob("*"))
        if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc"
    }


def snapshot() -> None:
    """Record the digest of every guarded root that exists."""
    for root in GUARDED_ROOTS:
        if root.is_dir():
            _STATE[root] = _digest(root)


def check(session) -> None:
    """Fail the session when a guarded root changed since :func:`snapshot`."""
    drifted = []
    for root, before in _STATE.items():
        after = _digest(root)
        drifted += [
            f"{root.name}/{name}"
            for name in sorted(set(before) | set(after))
            if before.get(name) != after.get(name)
        ]
    if not drifted:
        return
    session.exitstatus = 1
    message = "committed fixtures changed during the run:\n" + "\n".join(
        f"  {path}" for path in drifted
    )
    reporter = session.config.pluginmanager.get_plugin("terminalreporter")
    if reporter is not None:
        reporter.write_line(message, red=True)
    else:
        print(message)
